# Setting the Data Type
# In Python the data type is set when you assign a value to a variable

#str
name = "Daniel"

# print name
print(name)

#display the data type of name
print(type(name))

#int
age = 28

#display age
print(age)

#display data type of age
print(type(age))

#float
height = 1.75

#display height
print(height)

#display data type of height
print(type(height))

#complex
x = 1 + 2j

#display x
print(x)

#display the data type of x
print(type(x))

#list
fruits = ["apple", "banana", "cherry"]

#display fruits
print(fruits)

#display data type of fruits
print(type(fruits))

#tuple
favorite_fruits = ("banana", "orange", "cocao")

#display favorite_fruits
print(favorite_fruits)

#display data type of favorite_fruits
print(type(favorite_fruits))

#range
distance = range(6)

#display distance
print(distance)

#display type of distance
print(type(distance))
# for i in distance:
#     print(i)

#dict
user = {
    "name": "Daniel",
    "age": 34,
    "weight": 1.75
}

#display user
print(user)

#display data type of user
print(type(user))

#set
plants = {"apple", "banana"}

#display plants
print(plants)

#display type of plants
print(type(plants))

#frozenset
x = frozenset({"apple", "banana"})

#display x
print(x)

#display type of x 
print(type(x))

#bool
is_active = True

#display is_active
print(is_active)

#display type of is_active
print(type(is_active))

#bytes
x = b'hello'

#display x
print(x)

#display type of x
print(type(x))

#bytearray
x = bytearray(5)

#display x
print(x)

#display type of x
print(type(x))

#memoryview
x = memoryview(bytes(5))

#display x
print(x)

#display type of x
print(type(x))

#None
x = None

#display x
print(x)

#display type of x
print(type(x))

